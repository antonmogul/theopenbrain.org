/*
 * retina-widgets-sql.mjs — writes the migration that puts Stuart's 1 October
 * 2026 widget set into the Retina chapter (OPENBRAIN-141):
 *
 *   node scripts/seed/retina-widgets-sql.mjs
 *   → supabase/migrations/20261021000000_retina_stuart_widgets.sql
 *
 * The HTML comes from src/widgets/uploads/retina-*.html (the files the
 * Studio checks run on in src/__tests__/widgetUploads.test.js) and the
 * titles and descriptions from src/widgets/uploads/index.js, so the database
 * copy can never drift from the reviewed files. Re-run it after changing
 * either; the migration is idempotent, so a re-push updates the rows.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

// index.js uses import.meta.glob (Vite only), so its list is read as text.
const UPLOADED_WIDGETS = (() => {
  const src = readFileSync(
    resolve(ROOT, "src/widgets/uploads/index.js"),
    "utf8"
  );
  const m = /export const UPLOADED_WIDGETS = (\[[\s\S]*?\n\]);/.exec(src);
  if (!m) throw new Error("UPLOADED_WIDGETS not found in uploads/index.js");
  return new Function(`return ${m[1]};`)();
})();
const OUT = resolve(
  ROOT,
  "supabase/migrations/20261021000000_retina_stuart_widgets.sql"
);

/**
 * Legacy figure → upload. `pane`: every paragraph carrying the legacy
 * figure gets the widget as its pane figure instead (the four OnOff and
 * four RetinalCellTypes paragraphs keep sharing one figure, as today).
 * `band`: the paragraph is an `animation_full` block, the chapter's
 * full-screen animation; it becomes a full-width widget band.
 */
export const MAPPING = [
  ["animationPhotoreceptors", "retina-photoreceptors", "pane"],
  ["animationPhototransduction", "retina-phototransduction", "band"],
  ["animationTheVisualCycle", "retina-visual-cycle", "band"],
  ["animationPupillaryLightreflex", "retina-pupillary-light-reflex", "band"],
  ["animationImpairedVision", "retina-refraction-errors", "band"],
  ["animationOnOff", "retina-on-off-bipolar-cells", "pane"],
  ["animationRetinalCellTypes", "retina-retinal-cell-types", "pane"],
  ["animationSynapticArchitecture", "retina-synaptic-architecture", "pane"],
  ["animationCenterSurroundReceptiveFields", "retina-center-surround", "pane"],
  ["animationDirectionSelectivity", "retina-direction-selectivity", "pane"],
  [
    "animationObjectMotionSensitivity",
    "retina-object-motion-sensitivity",
    "pane",
  ],
  ["animationRodVsConeCircuits", "retina-rod-vs-cone-circuits", "pane"],
  [
    "animationLightSensitiveGanglionCells",
    "retina-light-sensitive-ganglion-cells",
    "pane",
  ],
];

const CREDIT = "Stuart Trenholm";
const byslug = Object.fromEntries(UPLOADED_WIDGETS.map((w) => [w.slug, w]));
const slugs = [...MAPPING.map(([, slug]) => slug), "retina-retinabox"];

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
// The dollar-quoted strings the thumbnail script parses
// (scripts/timeline/capture-widget-thumbs.mjs, parseUploadsSql).
const t = (s) => {
  if (String(s).includes("$t$")) throw new Error("description contains $t$");
  return `$t$${s}$t$`;
};

function uploadInsert(slug) {
  const w = byslug[slug];
  if (!w) throw new Error(`${slug} is not in src/widgets/uploads/index.js`);
  const html = readFileSync(
    resolve(ROOT, `src/widgets/uploads/${slug}.html`),
    "utf8"
  );
  if (html.includes("$w$")) throw new Error(`${slug}.html contains $w$`);
  return `insert into public.widget_uploads (slug, title, description, author, ramp, html, status)
values (
  ${q(slug)},
  ${t(w.title)},
  ${t(w.description)},
  ${t(w.author)},
  ${q(w.ramp)},
  $w$${html}$w$,
  'published')
on conflict (slug) do update
  set title = excluded.title, description = excluded.description, author = excluded.author,
      ramp = excluded.ramp, html = excluded.html, status = excluded.status, updated_at = now();
`;
}

