const mappingValues = MAPPING.map(
  ([key, slug, mode]) =>
    `      (${q(key)}, ${q(slug)}, ${q(byslug[slug].title)}, ${q(mode)})`
).join(",\n");

const attach = `do $$
declare
  chapter_id uuid;
  m record;
  old_id uuid;
  new_id uuid;
  n integer;
  total integer := 0;
begin
  select id into chapter_id from public.modules where slug = 'the-retina';
  if chapter_id is null then
    raise notice 'Retina widgets: no the-retina module, skipped';
    return;
  end if;

  for m in
    select * from (values
${mappingValues}
    ) as t(old_key, slug, title, mode)
  loop
    insert into public.animations
      (animation_key, title, media_type, interaction_type, component_name,
       config, scientific_domain, load_priority)
    values (
      'widget-upload:' || m.slug, m.title,
      'widget', 'click_states', 'IllustrationWidget',
      jsonb_build_object('widgetId', 'upload:' || m.slug, 'credit', ${q(CREDIT)}),
      'retina', 'low')
    on conflict (animation_key) do update
      set title = excluded.title, media_type = excluded.media_type,
          component_name = excluded.component_name,
          config = excluded.config, updated_at = now()
    returning id into new_id;

    select id into old_id from public.animations where animation_key = m.old_key;
    if old_id is null then
      raise notice 'Retina widgets: no % row, % not placed', m.old_key, m.slug;
      continue;
    end if;

    if m.mode = 'pane' then
      update public.paragraphs p
         set animation_id = new_id, has_animation = true,
             animation_trigger = 'auto', updated_at = now()
        from public.sections s
       where p.section_id = s.id and s.module_id = chapter_id
         and p.animation_id = old_id;
    else
      update public.paragraphs p
         set content = jsonb_build_object('blocks', jsonb_build_array(jsonb_build_object(
               'type', 'widget',
               'widgetId', 'upload:' || m.slug,
               'kind', 'inline',
               'title', m.title,
               'credit', ${q(CREDIT)}))),
             content_text = m.title,
             animation_id = null, has_animation = false, updated_at = now()
        from public.sections s
       where p.section_id = s.id and s.module_id = chapter_id
         and p.animation_id = old_id
         and p.content -> 'blocks' -> 0 ->> 'type' = 'animation_full';
    end if;
    get diagnostics n = row_count;
    total := total + n;
    raise notice 'Retina widgets: % -> % (%): % paragraph(s)', m.old_key, m.slug, m.mode, n;
  end loop;

  update public.sections
     set title = 'Story of the eye'
   where module_id = chapter_id and title = 'Story of the eye (EDIT)';
  get diagnostics n = row_count;

  raise notice 'Retina widgets: % paragraph(s) re-pointed; "Story of the eye" title fixed (% row)', total, n;
end $$;
`;

const sql = header + slugs.map(uploadInsert).join("\n") + "\n" + attach;
writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${(sql.length / 1024 / 1024).toFixed(1)} MB)`);
