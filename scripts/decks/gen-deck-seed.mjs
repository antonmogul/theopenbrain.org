#!/usr/bin/env node
/**
 * gen-deck-seed.mjs — write supabase/migrations/20261007010100_seed_funding_deck.sql
 * from FUNDING_DECK in src/data/decks/funding.js (OPENBRAIN-129).
 *
 *   npm run deck:seed-sql            # (re)write the migration
 *   npm run deck:seed-sql -- --check # exit 1 if the file is out of date
 *
 * The migration inserts the funding deck as the published deck shown at
 * /deck (slug "funding"), with its first revision row. It is `on conflict
 * (slug) do nothing`, so it never overwrites a deck edited in the dashboard;
 * once it has been pushed, changing funding.js changes only the bundled
 * fallback, not the database.
 *
 * The JSON goes in a $deck$ dollar-quoted string, written as UTF-8 exactly as
 * JSON.stringify(FUNDING_DECK, null, 2) prints it; the script refuses data
 * that contains "$deck$".
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../.."
);
const SOURCE = "src/data/decks/funding.js";
const OUT = "supabase/migrations/20261007010100_seed_funding_deck.sql";
const TITLE = "The Open Brain — Funding deck";

// funding.js is an ES module with no imports in a package without
// "type": "module"; loading it from a data: URL runs it as a module on every
// Node version CI uses, without the typeless-package warning.
const code = await readFile(path.join(root, SOURCE), "utf8");
const { FUNDING_DECK } = await import(
  `data:text/javascript;base64,${Buffer.from(code, "utf8").toString("base64")}`
);
if (!Array.isArray(FUNDING_DECK) || !FUNDING_DECK.length)
  throw new Error(`${SOURCE} exports no FUNDING_DECK entries`);

const json = JSON.stringify(FUNDING_DECK, null, 2);
if (json.includes("$deck$"))
  throw new Error(
    `${SOURCE} contains "$deck$", which would end the SQL string`
  );

const sql = `-- OPENBRAIN-129: the funding deck, published and shown at /deck.
--
-- GENERATED by scripts/decks/gen-deck-seed.mjs (npm run deck:seed-sql) from
-- ${SOURCE}. Do not edit by hand: change the source and regenerate.
--
-- It inserts the deck (slug "funding") as published, with the same slides as
-- the working copy and the snapshot, and its first deck_revisions row. It
-- shows the deck at /deck unless another deck already is. Re-running it never
-- overwrites dashboard edits: an existing "funding" deck is left alone
-- (on conflict do nothing), and then no revision row is added either.
--
-- Push after 20261007010000_decks.sql.

with src as (select $deck$${json}$deck$::jsonb as s),
inserted as (
  insert into public.decks
    (slug, title, kind, status, slides, published_slides, published_title,
     published_version, published_at, version, pinned)
  select 'funding', '${TITLE}', 'funding', 'published',
         src.s, src.s, '${TITLE}', 1, now(), 1,
         not exists (select 1 from public.decks where pinned)
  from src
  on conflict (slug) do nothing
  returning id, version, title, slides, schema_version
)
insert into public.deck_revisions (deck_id, version, title, slides, schema_version, note)
select id, version, title, slides, schema_version, 'Seeded from ${SOURCE}'
from inserted;
`;

const target = path.join(root, OUT);
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== sql) {
    console.error(`${OUT} is out of date: run npm run deck:seed-sql`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${FUNDING_DECK.length} slides).`);
} else {
  await writeFile(target, sql, "utf8");
  console.log(
    `Wrote ${OUT} (${FUNDING_DECK.length} slides, ${Buffer.byteLength(json)} bytes of JSON).`
  );
}
